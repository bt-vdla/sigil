import Foundation
import Observation
import OSLog

private let logger = Logger(subsystem: "com.sigil.app", category: "IconStore")

@Observable
final class IconStore: @unchecked Sendable {
    // MARK: - Published State

    private(set) var allIcons: [IconModel] = []
    private(set) var isLoading = true
    private(set) var loadedPackCounts: [IconPack: Int] = [:]
    private var iconsByID: [String: IconModel] = [:]

    // MARK: - Computed

    var totalCount: Int { allIcons.count }

    func icon(id: String) -> IconModel? { iconsByID[id] }

    // MARK: - Loading built-ins

    func loadIcons() async {
        let result = await Task.detached(priority: .userInitiated) {
            let tags = Self.loadTags()
            var all: [IconModel] = []
            var counts: [IconPack: Int] = [:]

            for pack in IconPack.builtIns {
                let packIcons = Self.loadBuiltInPack(pack, tags: tags[pack.id] ?? [:])
                counts[pack] = packIcons.count
                all.append(contentsOf: packIcons)
            }

            all.sort { $0.name < $1.name }
            return (all, counts)
        }.value

        await MainActor.run {
            // Custom packs may have loaded first
            self.allIcons = (self.allIcons + result.0).sorted { $0.name < $1.name }
            self.loadedPackCounts.merge(result.1) { _, new in new }
            self.rebuildIndex()
            self.isLoading = false
        }
    }

    // MARK: - Loading custom packs

    func loadCustomPack(_ pack: IconPack, svgDirectory: URL) async {
        let icons = await Task.detached(priority: .userInitiated) {
            Self.loadSVGsFromDirectory(pack, directory: svgDirectory, tags: [:])
        }.value

        await MainActor.run {
            // Remove any stale entries from a previous load of the same pack
            allIcons.removeAll { $0.pack.id == pack.id }
            allIcons.append(contentsOf: icons)
            allIcons.sort { $0.name < $1.name }
            loadedPackCounts[pack] = icons.count
            rebuildIndex()
        }
    }

    func unloadCustomPack(id: String) {
        guard let pack = loadedPackCounts.keys.first(where: { $0.id == id }) else { return }
        allIcons.removeAll { $0.pack.id == id }
        loadedPackCounts.removeValue(forKey: pack)
        rebuildIndex()
    }

    private func rebuildIndex() {
        iconsByID = Dictionary(allIcons.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first })
    }

    // MARK: - Private loading helpers

    /// tags.json: pack id → icon name → keywords. Generated by scripts/build-tags.py.
    private static func loadTags() -> [String: [String: [String]]] {
        guard let url = Bundle.main.url(forResource: "tags", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let tags = try? JSONDecoder().decode([String: [String: [String]]].self, from: data) else {
            logger.error("tags.json missing, search falls back to names only")
            return [:]
        }
        return tags
    }

    private static func loadBuiltInPack(_ pack: IconPack, tags: [String: [String]]) -> [IconModel] {
        guard let resourceURL = Bundle.main.resourceURL else {
            logger.error("Failed to locate bundle resource URL")
            return []
        }
        let iconsDir = resourceURL
            .appendingPathComponent("Icons", isDirectory: true)
            .appendingPathComponent(pack.directoryName, isDirectory: true)
            .standardized

        guard FileManager.default.fileExists(atPath: iconsDir.path) else {
            logger.error("Missing icon directory: \(iconsDir.path, privacy: .public)")
            return []
        }
        return loadSVGsFromDirectory(pack, directory: iconsDir, tags: tags)
    }

    private static func loadSVGsFromDirectory(_ pack: IconPack, directory: URL, tags: [String: [String]]) -> [IconModel] {
        guard FileManager.default.fileExists(atPath: directory.path) else { return [] }
        guard let files = try? FileManager.default.contentsOfDirectory(
            at: directory,
            includingPropertiesForKeys: [.isRegularFileKey],
            options: [.skipsHiddenFiles, .skipsSubdirectoryDescendants]
        ) else {
            logger.error("Failed to read contents of: \(directory.path, privacy: .public)")
            return []
        }

        return files.compactMap { url -> IconModel? in
            guard url.pathExtension.lowercased() == "svg",
                  let svgString = try? String(contentsOf: url, encoding: .utf8) else { return nil }
            let name = url.deletingPathExtension().lastPathComponent
            return IconModel(name: name, pack: pack, svgString: svgString, keywords: tags[name] ?? [])
        }
    }

    // MARK: - Search

    /// Ranked search. Empty query returns everything (name order).
    /// - packs: restrict to these pack ids; empty means all packs.
    /// - boost: extra score per icon id (favourites, recents).
    func search(query: String, packs: Set<String> = [], hidden: Set<String> = [], boost: [String: Int] = [:]) -> [IconModel] {
        let base = allIcons.filter { !hidden.contains($0.pack.id) && (packs.isEmpty || packs.contains($0.pack.id)) }

        let trimmed = query.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !trimmed.isEmpty else { return base }

        // Bulk mode: comma, newline, or "+" separated list of names
        let bulkTerms = trimmed
            .components(separatedBy: CharacterSet(charactersIn: ",+\n"))
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
        if bulkTerms.count > 1 {
            return bulkSearch(terms: bulkTerms, in: base)
        }

        // Every word has to match something; "arrow left" also matches the name "arrow-left" as a phrase
        let words = trimmed.split(whereSeparator: { $0 == " " || $0 == "-" || $0 == "_" }).map(String.init)
        guard !words.isEmpty else { return base }
        let phrase = words.joined(separator: "-")
        let expansions = words.map { Synonyms.lookup[$0] ?? [] }

        var scored: [(icon: IconModel, score: Int)] = []
        scored.reserveCapacity(base.count / 8)

        iconLoop: for icon in base {
            var total = 0
            for (word, synonyms) in zip(words, expansions) {
                let s = Self.score(word: word, synonyms: synonyms, icon: icon)
                if s == 0 { continue iconLoop }
                total += s
            }
            if words.count > 1 {
                if icon.nameLowercased == phrase { total += 2000 }
                else if icon.nameLowercased.hasPrefix(phrase) { total += 1000 }
            }
            scored.append((icon, total + (boost[icon.id] ?? 0)))
        }

        return scored
            .sorted {
                if $0.score != $1.score { return $0.score > $1.score }
                if $0.icon.name.count != $1.icon.name.count { return $0.icon.name.count < $1.icon.name.count }
                return $0.icon.name < $1.icon.name
            }
            .map(\.icon)
    }

    /// One query word against one icon, best tier wins. 0 means no match.
    static func score(word: String, synonyms: Set<String>, icon: IconModel) -> Int {
        let name = icon.nameLowercased
        if name == word { return 1000 }
        // Name-based tiers lose a little per extra word, so "trash" beats "http-delete" for "delete"
        let extraWords = 30 * max(0, icon.nameWords.count - 1)
        if icon.nameWords.first == word { return 900 - extraWords }
        if icon.nameWords.contains(word) { return 850 - extraWords }
        if !synonyms.isEmpty, icon.nameWords.contains(where: synonyms.contains) { return 830 - extraWords }
        // Partial word: "clos" → "closed"
        if icon.nameWords.contains(where: { $0.hasPrefix(word) }) { return 780 - extraWords }
        if icon.keywords.contains(word) { return 700 }
        if !synonyms.isEmpty, !icon.keywords.isDisjoint(with: synonyms) { return 650 }
        if word.count >= 2, icon.keywords.contains(where: { $0.hasPrefix(word) }) { return 600 }
        if word.count >= 3, name.contains(word) { return 400 }

        // Typos: one edit for 4+ letters, two for 7+ ("trahs" → trash, "calender" → calendar)
        if word.count >= 4 {
            let limit = word.count >= 7 ? 2 : 1
            let bytes = Array(word.utf8)
            if icon.tokenBytes.contains(where: { editDistance(bytes, $0, limit: limit) <= limit }) { return 300 }
        }
        if word.count >= 2, icon.initials.hasPrefix(word) { return 250 }
        return 0
    }

    /// Closest known word when nothing matched, for "Did you mean …?".
    func suggestion(for query: String) -> String? {
        guard let word = query.lowercased().split(separator: " ").last.map(String.init), word.count >= 3 else { return nil }
        let bytes = Array(word.utf8)
        var best: (word: [UInt8], distance: Int)?
        for icon in allIcons {
            for token in icon.tokenBytes where token.count > 2 {
                let d = Self.editDistance(bytes, token, limit: 3)
                if d <= 3, d < (best?.distance ?? .max) { best = (token, d) }
            }
        }
        return best.map { String(decoding: $0.word, as: UTF8.self) }
    }

    /// Optimal string alignment distance, giving up once it exceeds `limit`.
    static func editDistance(_ a: [UInt8], _ b: [UInt8], limit: Int) -> Int {
        if abs(a.count - b.count) > limit { return limit + 1 }
        if a.isEmpty || b.isEmpty { return max(a.count, b.count) }
        var prev2 = [Int](repeating: 0, count: b.count + 1)
        var prev = Array(0...b.count)
        var cur = [Int](repeating: 0, count: b.count + 1)
        for i in 1...a.count {
            cur[0] = i
            var rowMin = i
            for j in 1...b.count {
                let cost = a[i - 1] == b[j - 1] ? 0 : 1
                var v = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost)
                if i > 1, j > 1, a[i - 1] == b[j - 2], a[i - 2] == b[j - 1] {
                    v = min(v, prev2[j - 2] + 1)
                }
                cur[j] = v
                rowMin = min(rowMin, v)
            }
            if rowMin > limit { return limit + 1 }
            (prev2, prev, cur) = (prev, cur, prev2)
        }
        return prev[b.count]
    }

    /// Bulk search: strict matching only — exact name, prefix, or whole-word match.
    private func bulkSearch(terms: [String], in icons: [IconModel]) -> [IconModel] {
        let termSet = Set(terms)
        return icons.filter { icon in
            termSet.contains(icon.nameLowercased)
                || terms.contains { term in
                    icon.nameLowercased.hasPrefix(term + "-") || icon.nameWords.contains(term)
                }
        }
    }
}

